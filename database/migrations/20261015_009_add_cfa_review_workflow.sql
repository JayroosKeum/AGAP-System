USE remastered_db;

CREATE TABLE IF NOT EXISTS cfa_requests (
    cfa_request_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    request_id CHAR(36) NOT NULL,
    case_id BIGINT UNSIGNED NOT NULL,
    requesting_party_id BIGINT UNSIGNED NULL,
    source_outcome_id BIGINT UNSIGNED NOT NULL,
    source_hearing_id BIGINT UNSIGNED NOT NULL,
    ground_code VARCHAR(80) NOT NULL,
    ground_details TEXT NULL,
    request_status VARCHAR(40) NOT NULL DEFAULT 'Submitted',
    requested_by BIGINT UNSIGNED NOT NULL,
    requested_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by BIGINT UNSIGNED NULL,
    reviewed_at DATETIME NULL,
    review_decision VARCHAR(30) NULL,
    review_notes TEXT NULL,
    returned_at DATETIME NULL,
    rejected_at DATETIME NULL,
    approved_at DATETIME NULL,
    PRIMARY KEY (cfa_request_id),
    UNIQUE KEY uq_cfa_requests_request (request_id),
    KEY idx_cfa_requests_case_status (case_id, request_status),
    KEY idx_cfa_requests_outcome (source_outcome_id),
    KEY idx_cfa_requests_hearing (source_hearing_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cfa_certificates (
    certificate_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    cfa_request_id BIGINT UNSIGNED NOT NULL,
    case_id BIGINT UNSIGNED NOT NULL,
    certificate_number VARCHAR(80) NOT NULL,
    form_code VARCHAR(30) NOT NULL,
    legal_ground_code VARCHAR(80) NOT NULL,
    issuer_user_id BIGINT UNSIGNED NOT NULL,
    attesting_user_id BIGINT UNSIGNED NOT NULL,
    issued_at DATETIME NOT NULL,
    document_id BIGINT UNSIGNED NOT NULL,
    verification_code CHAR(36) NOT NULL,
    release_status VARCHAR(30) NOT NULL DEFAULT 'Not Released',
    released_to_party_id BIGINT UNSIGNED NULL,
    released_at DATETIME NULL,
    release_method VARCHAR(50) NULL,
    superseded_by_certificate_id BIGINT UNSIGNED NULL,
    voided_by BIGINT UNSIGNED NULL,
    voided_at DATETIME NULL,
    void_reason VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (certificate_id),
    UNIQUE KEY uq_cfa_certificate_request (cfa_request_id),
    UNIQUE KEY uq_cfa_certificate_number (certificate_number),
    UNIQUE KEY uq_cfa_verification_code (verification_code),
    KEY idx_cfa_certificate_case (case_id, issued_at),
    KEY idx_cfa_certificate_document (document_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
